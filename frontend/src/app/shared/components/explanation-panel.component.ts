/**
 * Explanation panel component — reusable display for LLM-generated explanations.
 *
 * Pure presentational: no HTTP calls inside. The parent component fetches the
 * explanation and passes state + text via signal inputs. Four states:
 *
 *   loading     — "GENERATING EXPLANATION…" spinner
 *   available   — yellow block with explanation text + source badge + caption
 *   unavailable — neutral message with the API's reason
 *   error       — error state with Retry button (parent handles retry)
 *
 * The explanation text is rendered as plain text via interpolation, never as
 * HTML, because it is LLM output that must not be trusted with innerHTML.
 */

import { Component, input, output } from '@angular/core';
import { ErrorStateComponent } from './error-state.component';
import { LoadingStateComponent } from './loading-state.component';
import type { ExplanationSource } from '../../core/models/api.models';

export type ExplanationState = 'loading' | 'available' | 'unavailable' | 'error';

@Component({
  selector: 'app-explanation-panel',
  standalone: true,
  imports: [LoadingStateComponent, ErrorStateComponent],
  template: `
    <section class="explanation-panel" aria-label="AI explanation">
      <div class="explanation-panel__header text-micro mono">[ AI EXPLANATION ]</div>

      @switch (state()) {
        @case ('loading') {
          <app-loading-state message="GENERATING EXPLANATION…" />
        }

        @case ('available') {
          <div class="explanation-panel__body">
            <p class="explanation-panel__text mono">{{ text() }}</p>
            <div class="explanation-panel__meta">
              @if (source()) {
                <span class="source-badge mono" [class.source-badge--llm]="source() === 'llm'" [class.source-badge--fallback]="source() === 'fallback'" [class.source-badge--mock]="source() === 'mock'">
                  {{ source() }}
                </span>
              }
              @if (generatedAt()) {
                <span class="generated-at mono">{{ generatedAt() }}</span>
              }
            </div>
            <p class="explanation-panel__caption mono">
              Generated by an LLM from the numbers shown. All numbers come from the analytical models.
            </p>
          </div>
        }

        @case ('unavailable') {
          <div class="explanation-panel__unavailable">
            <p class="mono">{{ reason() }}</p>
          </div>
        }

        @case ('error') {
          <app-error-state [message]="reason() ?? 'Failed to load explanation.'" (retry)="retry.emit()" />
        }
      }
    </section>
  `,
  styles: `
    .explanation-panel {
      border: var(--border-width) solid var(--color-ink);
      border-radius: var(--border-radius);
      box-shadow: var(--shadow-base);
      overflow: hidden;
    }

    .explanation-panel__header {
      padding: var(--spacing-sm) var(--spacing-md);
      background: var(--color-ink);
      color: var(--color-lime);
      letter-spacing: var(--letter-spacing-wide);
    }

    .explanation-panel__body {
      padding: var(--spacing-md) var(--spacing-lg);
      background: var(--color-yellow);
    }

    .explanation-panel__text {
      font-family: var(--font-mono);
      font-size: var(--font-size-base);
      line-height: var(--line-height-relaxed);
      white-space: pre-wrap;
      word-break: break-word;
      margin-bottom: var(--spacing-md);
    }

    .explanation-panel__meta {
      display: flex;
      align-items: center;
      gap: var(--spacing-sm);
      margin-bottom: var(--spacing-sm);
      flex-wrap: wrap;
    }

    .source-badge {
      display: inline-block;
      padding: 2px var(--spacing-sm);
      border: var(--border-width) solid var(--color-ink);
      border-radius: var(--border-radius);
      font-size: var(--font-size-micro);
      text-transform: uppercase;
      letter-spacing: var(--letter-spacing-wide);
      font-weight: var(--font-weight-bold);
      background: white;
    }

    .source-badge--llm {
      background: var(--color-teal);
      color: white;
    }

    .source-badge--fallback {
      background: var(--color-yellow);
    }

    .source-badge--mock {
      background: var(--color-pink);
      color: white;
    }

    .generated-at {
      font-size: var(--font-size-micro);
      opacity: 0.6;
    }

    .explanation-panel__caption {
      font-size: var(--font-size-micro);
      opacity: 0.65;
      margin-top: var(--spacing-sm);
      line-height: var(--line-height-normal);
    }

    .explanation-panel__unavailable {
      padding: var(--spacing-lg);
      background: rgba(0, 0, 0, 0.03);
      text-align: center;

      p {
        font-size: var(--font-size-small);
        opacity: 0.7;
        max-width: 50ch;
        margin: 0 auto;
        line-height: var(--line-height-normal);
      }
    }
  `,
})
export class ExplanationPanelComponent {
  /** Current state: loading | available | unavailable | error */
  state = input.required<ExplanationState>();

  /** The explanation text — rendered as plain text, never HTML */
  text = input<string | null>(null);

  /** Reason shown when unavailable or error */
  reason = input<string | null>(null);

  /** Source of the explanation: llm | fallback | mock | null */
  source = input<ExplanationSource>(null);

  /** Timestamp the explanation was generated */
  generatedAt = input<string | null>(null);

  /** Emitted when the user clicks Retry in the error state */
  retry = output<void>();
}
